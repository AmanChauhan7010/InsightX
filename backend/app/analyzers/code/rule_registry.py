    @classmethod
    def get(cls, rule_id: str) -> Optional[RuleDefinition]:
        return cls.RULES.get(rule_id)

    @classmethod
    def list_rules(cls, language: Optional[str] = None) -> List[Dict[str, object]]:
        items = cls.RULES.values()
        if language:
            items = [r for r in items if language.lower() in r.languages]
        return [r.to_dict() for r in items]
