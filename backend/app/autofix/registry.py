    @classmethod
    def get(cls, rule_id: Optional[str]) -> Optional[AutoFixDefinition]:
        if not rule_id:
            return None
        return cls.DEFINITIONS.get(rule_id)

    @classmethod
    def list_supported(cls) -> List[Dict[str, object]]:
        return [d.to_dict() for d in cls.DEFINITIONS.values()]
